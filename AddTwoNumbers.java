public class AddTwoNumbers {
    public static void main(String[] args) {
        // Declare two numbers
        int num1 = 10;
        int num2 = 20;
        
        // Add the two numbers
        int sum = num1 + num2;
        
        // Display the result
        System.out.println("Number 1: " + num1);
        System.out.println("Number 2: " + num2);
        System.out.println("Sum: " + sum);
    }
}
